DEMO_DIR = os.path.join(L.HERE, "docs", "demo")


def last_full_month(now: Optional[datetime.date] = None) -> str:
    d = (now or datetime.date.today()).replace(day=1) - datetime.timedelta(days=1)
    return d.strftime("%Y-%m")


def build_demo(top: int = 10, period: Optional[str] = None, out_dir: Optional[str] = None,
               db_path: Optional[str] = None) -> dict:
    """Packs for the top named (verified) sellers in a month -> docs/demo/.

    Seller packs only: sellers are public businesses with published endpoints.
    Buyer packs are never published (buyers are not named or profiled)."""
    import yaml
    out_dir = out_dir or DEMO_DIR
    period = period or last_full_month()
    res = L.run_labels(write=False, db_path=db_path)
    cfg = {}
    try:
        cfg = yaml.safe_load(open(os.path.join(L.HERE, "config.yaml"))) or {}
    except Exception:
        pass
    rev = defaultdict(float)
    for p in res["payments"]:
        if p["ts"].startswith(period) and p["leg_type"] in L.PAYMENT_LEGS:
            rev[p["payee"]] += p["amount_usdc"]
    named = [w for w in rev if res["wallets"].get(w, {}).get("tier") == "verified"
             and "seller" in res["wallets"][w].get("roles", [])]
    named.sort(key=lambda w: -rev[w])
    if os.path.isdir(out_dir):
        import shutil
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    rows = []
    for w in named[:top]:
        pk = build_pack(w, period, res, role="seller", accounting=cfg.get("accounting"))
        sub = os.path.join("".join(ch for ch in w if ch.isalnum())[:64], period)
        write_pack(pk, os.path.join(out_dir, sub))
        rows.append({"wallet": w, "name": pk["name"], "chain": pk["chain"], "path": sub + "/index.html",
                     "total": pk["summary"]["total"], "payments": pk["summary"]["payments"],
                     "buyers": pk["summary"]["counterparties"], "invoices": len(pk["invoices"]),
                     "exceptions": len(pk["exceptions"]), "tie_out": pk["tie_out"]["all_pass"]})
    with open(os.path.join(out_dir, "index.html"), "w") as f:
        f.write(render_demo_index(period, rows))
    with open(os.path.join(out_dir, "index.json"), "w") as f:
        json.dump({"period": period, "packs": rows}, f, indent=1)
    return {"period": period, "packs": rows, "out_dir": out_dir}


