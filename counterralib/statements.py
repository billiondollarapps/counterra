def fmt_price(x):
    x = float(x)
    if x >= 1:
        return "${:,.2f}".format(x)
    s = "{:.6f}".format(x).rstrip("0").rstrip(".")
    return "$" + s


def signed6(x):
    x = float(x)
    return ("-" if x < 0 else "") + "${:,.6f}".format(abs(x))


def money(x):
    return "${:,.2f}".format(float(x))


def e(s):
    return html.escape(str(s if s is not None else ""), quote=True)


def tx_url(chain, tx):
    return ("https://solscan.io/tx/" if chain == "solana" else "https://basescan.org/tx/") + tx


def addr_url(chain, a):
    return ("https://solscan.io/account/" if chain == "solana" else "https://basescan.org/address/") + a


