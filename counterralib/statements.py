def verify_exports(pack: dict, qb_path: str, xero_path: str):
    """Re-read the written journal files and add real checks to the tie-out:
    each file balances, and its revenue/spend side equals the statement."""
    def sums(path, dcol, ccol):
        d = c = 0.0
        with open(path) as f:
            for row in csv.DictReader(f):
                d += float(row[dcol] or 0)
                c += float(row[ccol] or 0)
        return round(d, 2), round(c, 2)
    qd, qc = sums(qb_path, "Debit", "Credit")
    xd, xc = sums(xero_path, "*Debit", "*Credit")
    escrow = round(sum(j["amount_usd"] for j in pack["journal"] if j["category"] == "Escrow deposit"), 2)
    t = pack["tie_out"]
    target = round(t["journal"] + escrow, 2)
    t["checks"] += [
        {"check": "QuickBooks file balances (debits = credits)", "pass": qd == qc},
        {"check": "Xero file balances (debits = credits)", "pass": xd == xc},
        {"check": "QuickBooks and Xero files total the statement", "pass": qd == target and xd == target},
    ]
    t["exports"] = {"quickbooks_debits": qd, "xero_debits": xd}
    t["all_pass"] = all(c["pass"] for c in t["checks"])


def write_pack(pack: dict, out_dir: str, make_zip: bool = True) -> str:
    os.makedirs(os.path.join(out_dir, "invoices"), exist_ok=True)
    for f in os.listdir(os.path.join(out_dir, "invoices")):
        os.remove(os.path.join(out_dir, "invoices", f))
    pack["_zip"] = make_zip
    # Exports first, then READ THEM BACK: the tie-out must check the files a
    # user will actually import, not the numbers we meant to write.
    qb = os.path.join(out_dir, "journal_quickbooks.csv")
    xr = os.path.join(out_dir, "journal_xero.csv")
    write_quickbooks_csv(pack["journal"], qb)
    write_xero_csv(pack["journal"], xr)
    verify_exports(pack, qb, xr)
    with open(os.path.join(out_dir, "index.html"), "w") as f:
        f.write(render_statement(pack))
    for inv in pack["invoices"]:
        with open(os.path.join(out_dir, "invoices", inv["number"] + ".html"), "w") as f:
            f.write(render_invoice(pack, inv))
    pj = {k: v for k, v in pack.items() if not k.startswith("_")}
    with open(os.path.join(out_dir, "pack.json"), "w") as f:
        json.dump(pj, f, indent=1)
    with open(os.path.join(out_dir, "payments.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["timestamp_utc", "tx_hash", "counterparty", "amount_usdc", "path",
                    "facilitator", "category", "flags", "invoice"])
        inv_of = {}
        for inv in pack["invoices"]:
            for p in inv["payments"]:
                inv_of[(p["tx"], p["ts"], p["amount"])] = inv["number"]
        for p in pack["payments"]:
            w.writerow([p["ts"], p["tx"], p["counterparty"], "%.6f" % p["amount"], p["path"],
                        p["facilitator"], p["category"], ",".join(p["flags"]),
                        inv_of.get((p["tx"], p["ts"], p["amount"]), "")])
    with open(os.path.join(out_dir, "exceptions.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["severity", "type", "counterparty", "amount_usd", "payments", "detail"])
        for x in pack["exceptions"]:
            w.writerow([x["severity"], x["type"], x["counterparty"], "%.2f" % x["amount"], x["payments"], x["detail"]])
    if make_zip:
        zp = os.path.join(out_dir, "pack.zip")
        with zipfile.ZipFile(zp, "w", zipfile.ZIP_DEFLATED) as z:
            for root, _, files in os.walk(out_dir):
                for fn in files:
                    if fn == "pack.zip":
                        continue
                    full = os.path.join(root, fn)
                    z.write(full, os.path.relpath(full, out_dir))
    return os.path.join(out_dir, "index.html")


def run(wallet: str, period: Optional[str] = None, role: Optional[str] = None,
        issuer_path: Optional[str] = None, out_dir: Optional[str] = None,
        db_path: Optional[str] = None) -> dict:
    import yaml
    res = L.run_labels(write=False, db_path=db_path)
    w = _norm(wallet)
    if not period:
        months = sorted({p["ts"][:7] for p in res["payments"] if w in (p["payer"], p["payee"])})
        if not months:
            raise ValueError("no x402 activity for {} in the ledger".format(wallet))
        period = months[-1]
    issuer = json.load(open(issuer_path)) if issuer_path else None
    cfg = {}
    try:
        cfg = yaml.safe_load(open(os.path.join(L.HERE, "config.yaml"))) or {}
    except Exception:
        pass
    pack = build_pack(w, period, res, role=role, issuer=issuer, accounting=cfg.get("accounting"))
    out_dir = out_dir or os.path.join(L.HERE, "out", "statements",
                                      "".join(ch for ch in w if ch.isalnum())[:64], period)
    index = write_pack(pack, out_dir)
    return {"pack": pack, "index": index, "out_dir": out_dir}


