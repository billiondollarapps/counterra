REVENUE_ACCOUNT = "4100 - x402 Revenue"
SUSPENSE_ACCOUNT = "1990 - x402 Suspense (unidentified counterparty)"
ANON_CUSTOMER = "Anonymous x402 customers"
ASSET_ACCOUNT = "1085 - Digital Assets (USDC)"
LARGE_PAYMENT_USD = 40.0

