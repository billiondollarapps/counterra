"""
Monthly x402 statement packs - the documents x402 never produces.

For one wallet and one month, Counterra produces a complete close pack from
the decoded settlements:

  1. STATEMENT     every payment in the period, grouped by counterparty,
                   with totals - for a seller (revenue) or a buyer (spend)
  2. INVOICES      one per counterparty per month, numbered and dated, line
                   items grouped by unit price, every payment listed with its
                   transaction hash. Seller packs: invoices the seller ISSUES.
                   Buyer packs: invoices RECONSTRUCTED from what was paid.
  3. EXCEPTIONS    what an accountant will ask about: suspected address
                   poisoning, unidentified counterparties, wash/test flags,
                   batch-channel escrow legs, unusually large payments
  4. EXPORTS       QuickBooks + Xero journals, payments CSV, pack JSON
  5. TIE-OUT       proof the documents agree: payments total == statement
                   total == invoices total == journal total (to the cent,
                   rounding stated explicitly)

Honest scope - printed on every document:
  - Invoices are PAYMENT-BACKED: they evidence what was paid on-chain. They
    become tax invoices only when the issuer's legal name, address and tax
    ID are added (pass --issuer), and that treatment is jurisdiction-specific.
  - "x402 activity" means decoded x402 settlements, not the wallet's full
    balance: other transfers in and out of the wallet are not shown.
  - Coverage depends on the ledger: Base is sampled, so a pack built from
    the shared ledger can miss payments. A wallet's own full sweep
    (counterra.py books --wallet) is complete for that wallet.

Python 3.8-safe; stdlib only (html escaping, csv, zipfile).
"""

