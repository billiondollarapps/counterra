REVENUE_ACCOUNT = "4100 - x402 Revenue"
ASSET_ACCOUNT = "1085 - Digital Assets (USDC)"
LARGE_PAYMENT_USD = 40.0

DISCLAIMER = (
    "Generated by Counterra from public on-chain x402 settlements. Invoices are "
    "payment-backed records of what was paid; they become tax invoices only once the "
    "issuer's legal name, address and tax ID are added, and tax treatment depends on "
    "jurisdiction. Figures cover decoded x402 settlements only, not the wallet's full "
    "balance. Not tax or legal advice.")


def _norm(a):
    return L.norm(a)


def short(w: str) -> str:
    w = str(w)
    return w if len(w) <= 14 else w[:8] + "…" + w[-4:]


def code(w: str) -> str:
    """Short stable code for invoice numbers: last 6 alphanumerics, upper."""
    s = "".join(ch for ch in str(w) if ch.isalnum())
    return s[-6:].upper()


def period_bounds(period: str):
    y, m = int(period[:4]), int(period[5:7])
    start = datetime.date(y, m, 1)
    end = datetime.date(y + (m == 12), (m % 12) + 1, 1) - datetime.timedelta(days=1)
    return start, end


def cents(x: float) -> float:
    """Round half-up to cents (not banker's rounding) - what accountants expect."""
    from decimal import Decimal, ROUND_HALF_UP
    return float(Decimal(repr(float(x))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


